/** biome-ignore-all lint/suspicious/noTemplateCurlyInString: shell variable interpolation */

import type { CommandDef, CommandOption } from "../commands/command-def";
import { completionCommands } from "./command-metadata";
import { COMPLETION_PROFILES_FLAG } from "./completion-profiles";
import { COMPLETION_SHELLS, globalOptions } from "./global-options";

const COMMANDS = Object.values(completionCommands);

function flagNames(option: CommandOption): string[] {
  return [`--${option.name}`, ...(option.short ? [`-${option.short}`] : [])];
}

function quoteShell(value: string): string {
  return `'${value.replaceAll("'", "'\\''")}'`;
}

function zshOption(
  option: CommandOption & { values?: readonly string[] },
): string {
  const value =
    option.type === "string"
      ? `:${option.placeholder?.toLowerCase() || option.name}:${option.values ? `(${option.values.join(" ")})` : (option.completionValues?.replace(/^__/, "_") ?? "")}`
      : "";
  const description = `[${option.description}]${value}`;
  return option.short
    ? `${quoteShell(`(-${option.short} --${option.name})`)}{-${option.short},--${option.name}}${quoteShell(description)}`
    : quoteShell(`--${option.name}${description}`);
}

function getAllNames(command: CommandDef): Array<string> {
  return [command.name, ...(command.aliases ?? [])];
}

function quoteFish(value: string): string {
  const escaped = value.replaceAll("\\", "\\\\").replaceAll("'", "\\'");
  return `'${escaped}'`;
}

function generateFishCompletions(): string {
  const lines: Array<string> = [
    "# Fish completions for wct",
    "# Generated by: wct --completions fish",
    "",
    "# Erase inherited completions (e.g. from alias --wraps)",
    "complete -c wct -e",
    "",
    "# Disable file completions by default",
    "complete -c wct -f",
    "",
    "# Helper: list git branches for completion",
    "function __wct_branches",
    "    git branch --format='%(refname:short)' 2>/dev/null",
    "end",
    "",
    "# Helper: list branches that have worktrees",
    "function __wct_worktree_branches",
    "    git worktree list --porcelain 2>/dev/null | string match -rg '^branch refs/heads/(.+)$'",
    "end",
    "",
    "# Helper: list config profile names",
    "function __wct_profiles",
    // Fish string builtins split piped input into lines; pass NUL records as arguments.
    `    set -l profiles (command wct ${COMPLETION_PROFILES_FLAG} fish 2>/dev/null | string split0)`,
    "    if set -q profiles[1]",
    "        string escape --no-quoted -- $profiles",
    "    end",
    "end",
    "",
    "# Commands",
  ];

  for (const command of COMMANDS) {
    for (const name of getAllNames(command)) {
      lines.push(
        `complete -c wct -n '__fish_use_subcommand' -a ${quoteFish(name)} -d ${quoteFish(command.description)}`,
      );
    }

    if (command.subcommands) {
      const subNames = command.subcommands.map((s) => s.name).join(" ");
      for (const sub of command.subcommands) {
        lines.push(
          `complete -c wct -n '__fish_seen_subcommand_from ${command.name}; and not __fish_seen_subcommand_from ${subNames}' -a ${quoteFish(sub.name)} -d ${quoteFish(sub.description)}`,
        );
      }
      for (const sub of command.subcommands) {
        for (const option of sub.options ?? []) {
          const parts = [
            "complete -c wct",
            `-n '__fish_seen_subcommand_from ${command.name}; and __fish_seen_subcommand_from ${sub.name}'`,
          ];
          if (option.short) {
            parts.push(`-s ${option.short}`);
          }
          parts.push(`-l ${option.name}`);
          if (option.type === "string") {
            parts.push("-r");
            if (option.completionValues) parts.push("-f");
          }
          parts.push(`-d ${quoteFish(option.description)}`);
          if (option.completionValues) {
            parts.push(`-a '(${option.completionValues})'`);
          }
          lines.push(parts.join(" "));
        }

        if (sub.completionType === "path") {
          lines.push(
            `complete -c wct -n '__fish_seen_subcommand_from ${command.name}; and __fish_seen_subcommand_from ${sub.name}' -a '(__fish_complete_directories)' -d 'Path to repo'`,
          );
        }
      }
    }
  }

  lines.push("");
  lines.push("# Global options");
  for (const option of globalOptions) {
    const parts = ["complete -c wct"];
    if (option.short) parts.push(`-s ${option.short}`);
    parts.push(`-l ${option.name}`);
    if (option.type === "string") parts.push("-r", "-f");
    if (option.values) parts.push(`-a ${quoteFish(option.values.join(" "))}`);
    parts.push(`-d ${quoteFish(option.description)}`);
    lines.push(parts.join(" "));
  }

  lines.push("");
  lines.push("# Per-command options");

  for (const command of COMMANDS) {
    if (!command.options) continue;
    const names = getAllNames(command);
    for (const option of command.options) {
      const parts = [
        "complete -c wct",
        `-n '__fish_seen_subcommand_from ${names.join(" ")}'`,
      ];
      if (option.short) {
        parts.push(`-s ${option.short}`);
      }
      parts.push(`-l ${option.name}`);
      if (option.type === "string") {
        parts.push("-r");
        if (option.completionValues) parts.push("-f");
      }
      parts.push(`-d ${quoteFish(option.description)}`);
      if (option.completionValues) {
        parts.push(`-a '(${option.completionValues})'`);
      }
      lines.push(parts.join(" "));
    }
  }

  const branchCommands = COMMANDS.filter(
    (command) => command.completionType === "branch",
  )
    .flatMap((command) => getAllNames(command))
    .join(" ");

  const worktreeCommands = COMMANDS.filter(
    (command) => command.completionType === "worktree",
  )
    .flatMap((command) => getAllNames(command))
    .join(" ");

  if (branchCommands) {
    lines.push("");
    lines.push("# Branch completions");
    lines.push(
      `complete -c wct -n '__fish_seen_subcommand_from ${branchCommands}' -a '(__wct_branches)' -d 'Branch name'`,
    );
  }

  if (worktreeCommands) {
    lines.push("");
    lines.push("# Worktree branch completions");
    lines.push(
      `complete -c wct -n '__fish_seen_subcommand_from ${worktreeCommands}' -a '(__wct_worktree_branches)' -d 'Branch name'`,
    );
  }

  lines.push("");
  return lines.join("\n");
}

function generateBashCompletions(): string {
  const commandNames = COMMANDS.flatMap((command) => getAllNames(command)).join(
    " ",
  );
  const globalFlags = globalOptions.flatMap(flagNames).join(" ");
  const branchCommands = COMMANDS.filter(
    (command) => command.completionType === "branch",
  ).flatMap((command) => getAllNames(command));
  const worktreeCommands = COMMANDS.filter(
    (command) => command.completionType === "worktree",
  ).flatMap((command) => getAllNames(command));

  const lines: Array<string> = [
    "# Bash completions for wct",
    "# Generated by: wct --completions bash",
    "",
    "_wct_branches() {",
    "    git branch --format='%(refname:short)' 2>/dev/null",
    "}",
    "",
    "_wct_worktree_branches() {",
    "    git worktree list --porcelain 2>/dev/null | sed -n 's|^branch refs/heads/||p'",
    "}",
    "",
    "_wct_profiles() {",
    `    command wct ${COMPLETION_PROFILES_FLAG} bash 2>/dev/null`,
    "}",
    "",
    "_wct() {",
    '    local cur="${COMP_WORDS[COMP_CWORD]}"',
    '    local prev="${COMP_WORDS[COMP_CWORD-1]}"',
    '    local cword="$COMP_CWORD"',
    '    local cmd="${COMP_WORDS[1]}"',
    "    local cmd_index=1",
    "    local scan_index=1",
    "",
    ...globalOptions
      .filter((option) => option.values)
      .flatMap((option) => [
        `    if [[ "$prev" == "--${option.name}" ]]; then`,
        `        COMPREPLY=($(compgen -W '${option.values?.join(" ")}' -- "$cur"))`,
        "        return",
        "    fi",
      ]),
    '    if [[ "$cmd" == -* ]]; then',
    "        while [[ $scan_index -lt $cword ]]; do",
    '            local scan_word="${COMP_WORDS[scan_index]}"',
    `            if [[ ${globalOptions
      .filter((option) => option.type === "string")
      .map((option) => `"$scan_word" == "--${option.name}"`)
      .join(" || ")} ]]; then`,
    "                ((scan_index += 2))",
    "                continue",
    "            fi",
    '            if [[ "$scan_word" == -* ]]; then',
    "                ((scan_index++))",
    "                continue",
    "            fi",
    '            cmd="$scan_word"',
    "            cmd_index=$scan_index",
    "            break",
    "        done",
    "    fi",
    "",
    '    if [[ -z "$cmd" || "$cmd" == -* ]]; then',
    '        if [[ "$cur" == -* ]]; then',
    `            COMPREPLY=($(compgen -W '${globalFlags}' -- "$cur"))`,
    "        else",
    `            COMPREPLY=($(compgen -W '${commandNames}' -- "$cur"))`,
    "        fi",
    "        return",
    "    fi",
    "",
    '    case "$cmd" in',
  ];

  for (const command of COMMANDS) {
    if (command.subcommands) continue;
    const options: Array<string> = [];
    if (command.options) {
      for (const option of command.options) {
        options.push(`--${option.name}`);
        if (option.short) {
          options.push(`-${option.short}`);
        }
      }
    }
    const allNames = getAllNames(command);
    const isBranchCommand = allNames.some((name) =>
      branchCommands.includes(name),
    );
    const isWorktreeCommand = allNames.some((name) =>
      worktreeCommands.includes(name),
    );
    const completionFunction = isWorktreeCommand
      ? "_wct_worktree_branches"
      : "_wct_branches";

    lines.push(`        ${allNames.join("|")})`);
    const optionsWithCompletionValues = (command.options ?? []).filter(
      (option) => option.completionValues,
    );
    for (const option of optionsWithCompletionValues) {
      const prevCheck = option.short
        ? `"$prev" == "--${option.name}" || "$prev" == "-${option.short}"`
        : `"$prev" == "--${option.name}"`;
      const bashFunc = option.completionValues
        ? option.completionValues.replace(/^__/, "_")
        : option.completionValues;
      lines.push(`            if [[ ${prevCheck} ]]; then`);
      if (option.completionValues === "__wct_profiles") {
        // Filename completion can append a slash to a profile matching a directory.
        lines.push("                COMPREPLY=()");
        lines.push("                local profile quoted_profile");
        lines.push("                while IFS= read -r -d '' profile; do");
        lines.push(
          '                    [[ "$profile" == "$cur"* ]] || continue',
        );
        lines.push(
          '                    printf -v quoted_profile "%q" "$profile"',
        );
        lines.push('                    COMPREPLY+=("$quoted_profile")');
        lines.push("                done < <(_wct_profiles)");
      } else {
        lines.push(
          `                COMPREPLY=($(compgen -W "$(${bashFunc})" -- "$cur"))`,
        );
      }
      lines.push("                return");
      lines.push("            fi");
    }
    if (options.length > 0) {
      lines.push(
        `            COMPREPLY=($(compgen -W '${globalFlags} ${options.join(" ")}' -- "$cur"))`,
      );
    } else {
      lines.push(
        `            COMPREPLY=($(compgen -W '${globalFlags}' -- "$cur"))`,
      );
    }
    if (isBranchCommand || isWorktreeCommand) {
      if (options.length > 0) {
        lines.push('            if [[ "$cur" != -* ]]; then');
        lines.push(
          `                COMPREPLY=($(compgen -W "$(${completionFunction})" -- "$cur"))`,
        );
        lines.push("            fi");
      } else {
        lines.push(
          `            COMPREPLY=($(compgen -W "$(${completionFunction})" -- "$cur"))`,
        );
      }
    }
    lines.push("            ;;");
  }

  for (const command of COMMANDS) {
    if (!command.subcommands) continue;
    const subNames = command.subcommands.map((s) => s.name).join(" ");
    lines.push(`        ${command.name})`);
    lines.push('            local subcmd=""');
    lines.push("            local subcmd_index=$((cmd_index + 1))");
    lines.push("            while [[ $subcmd_index -lt $cword ]]; do");
    lines.push(
      '                local subcmd_word="${COMP_WORDS[subcmd_index]}"',
    );
    lines.push(
      `                if [[ ${globalOptions
        .filter((option) => option.type === "string")
        .map((option) => `"$subcmd_word" == "--${option.name}"`)
        .join(" || ")} ]]; then`,
    );
    lines.push("                    ((subcmd_index += 2))");
    lines.push("                    continue");
    lines.push("                fi");
    lines.push('                if [[ "$subcmd_word" == -* ]]; then');
    lines.push("                    ((subcmd_index++))");
    lines.push("                    continue");
    lines.push("                fi");
    lines.push('                subcmd="$subcmd_word"');
    lines.push("                break");
    lines.push("            done");
    lines.push('            if [[ -z "$subcmd" ]]; then');
    lines.push(
      `                COMPREPLY=($(compgen -W '${subNames}' -- "$cur"))`,
    );
    lines.push("            else");
    lines.push('                case "$subcmd" in');
    for (const sub of command.subcommands) {
      const subFlags = (sub.options ?? [])
        .flatMap((option) => [
          `--${option.name}`,
          ...(option.short ? [`-${option.short}`] : []),
        ])
        .join(" ");
      const stringValuePrevCheck = (sub.options ?? [])
        .filter((option) => option.type === "string")
        .map((option) =>
          option.short
            ? `"$prev" == "--${option.name}" || "$prev" == "-${option.short}"`
            : `"$prev" == "--${option.name}"`,
        )
        .join(" || ");
      const allFlags = subFlags ? `${globalFlags} ${subFlags}` : globalFlags;
      lines.push(`                    ${sub.name})`);
      if (sub.completionType === "path") {
        if (stringValuePrevCheck) {
          lines.push(
            `                        if [[ ${stringValuePrevCheck} ]]; then`,
          );
          lines.push("                            COMPREPLY=()");
          lines.push('                        elif [[ "$cur" != -* ]]; then');
        } else {
          lines.push('                        if [[ "$cur" != -* ]]; then');
        }
        lines.push(
          '                            COMPREPLY=($(compgen -d -- "$cur"))',
        );
        lines.push("                        else");
        lines.push(
          `                            COMPREPLY=($(compgen -W '${allFlags}' -- "$cur"))`,
        );
        lines.push("                        fi");
      } else {
        lines.push(
          `                        COMPREPLY=($(compgen -W '${allFlags}' -- "$cur"))`,
        );
      }
      lines.push("                        ;;");
    }
    lines.push("                esac");
    lines.push("            fi");
    lines.push("            ;;");
  }

  lines.push("    esac");
  lines.push('    if [[ ${#COMPREPLY[@]} -eq 0 && "$cur" == -* ]]; then');
  lines.push(`        COMPREPLY=($(compgen -W '${globalFlags}' -- "$cur"))`);
  lines.push("    fi");
  lines.push("}");
  lines.push("");
  lines.push("complete -F _wct wct");
  lines.push("");

  return lines.join("\n");
}

function generateZshCompletions(): string {
  const branchCommands = COMMANDS.filter(
    (command) => command.completionType === "branch",
  ).flatMap((command) => getAllNames(command));
  const worktreeCommands = COMMANDS.filter(
    (command) => command.completionType === "worktree",
  ).flatMap((command) => getAllNames(command));

  const lines: Array<string> = [
    "#compdef wct",
    "# Zsh completions for wct",
    "# Generated by: wct --completions zsh",
    "",
    "_wct_branches() {",
    "    local branches",
    "    branches=($(git branch --format='%(refname:short)' 2>/dev/null))",
    "    _describe 'branch' branches",
    "}",
    "",
    "_wct_worktree_branches() {",
    "    local branches",
    "    branches=($(git worktree list --porcelain 2>/dev/null | sed -n 's|^branch refs/heads/||p'))",
    "    _describe 'branch' branches",
    "}",
    "",
    "_wct_profiles() {",
    "    local -a profiles",
    '    profiles=("${(@Q)${(z)$(command wct ' +
      COMPLETION_PROFILES_FLAG +
      ' zsh 2>/dev/null)}}")',
    "    (( ${#profiles} )) && compadd -a profiles",
    "}",
    "",
    "_wct() {",
    "    local -a commands",
    "    commands=(",
  ];

  for (const command of COMMANDS) {
    for (const name of getAllNames(command)) {
      lines.push(`        ${quoteShell(`${name}:${command.description}`)}`);
    }
  }
  lines.push("    )");
  lines.push("");
  lines.push("    _arguments -C \\");
  for (const option of globalOptions) {
    lines.push(`        ${zshOption(option)} \\`);
  }
  lines.push("        '1:command:->command' \\");
  lines.push("        '*::arg:->args'");
  lines.push("");
  lines.push('    local command_word=""');
  lines.push("    local command_index=1");
  lines.push("    local scan_index=1");
  lines.push("    while (( scan_index < CURRENT )); do");
  lines.push('        local scan_word="$words[scan_index]"');
  lines.push(
    `        if [[ ${globalOptions
      .filter((option) => option.type === "string")
      .map((option) => `"$scan_word" == "--${option.name}"`)
      .join(" || ")} ]]; then`,
  );
  lines.push("            (( scan_index += 2 ))");
  lines.push("            continue");
  lines.push("        fi");
  lines.push('        if [[ "$scan_word" == -* ]]; then');
  lines.push("            (( scan_index++ ))");
  lines.push("            continue");
  lines.push("        fi");
  lines.push('        command_word="$scan_word"');
  lines.push("        command_index=$scan_index");
  lines.push("        break");
  lines.push("    done");
  lines.push("");
  lines.push('    case "$state" in');
  lines.push("        command)");
  lines.push("            _describe 'wct command' commands");
  lines.push("            ;;");
  lines.push("        args)");
  lines.push('            case "$command_word" in');

  for (const command of COMMANDS) {
    if (command.subcommands) {
      lines.push(`                ${command.name})`);
      lines.push('                    local subcmd=""');
      lines.push(
        "                    local subcmd_index=$((command_index + 1))",
      );
      lines.push("                    while (( subcmd_index < CURRENT )); do");
      lines.push(
        '                        local subcmd_word="$words[subcmd_index]"',
      );
      lines.push(
        `                        if [[ ${globalOptions
          .filter((option) => option.type === "string")
          .map((option) => `"$subcmd_word" == "--${option.name}"`)
          .join(" || ")} ]]; then`,
      );
      lines.push("                            (( subcmd_index += 2 ))");
      lines.push("                            continue");
      lines.push("                        fi");
      lines.push('                        if [[ "$subcmd_word" == -* ]]; then');
      lines.push("                            (( subcmd_index++ ))");
      lines.push("                            continue");
      lines.push("                        fi");
      lines.push('                        subcmd="$subcmd_word"');
      lines.push("                        break");
      lines.push("                    done");
      lines.push('                    if [[ -z "$subcmd" ]]; then');
      lines.push("                        local -a subcmds");
      lines.push("                        subcmds=(");
      for (const sub of command.subcommands) {
        lines.push(
          `                            ${quoteShell(`${sub.name}:${sub.description}`)}`,
        );
      }
      lines.push("                        )");
      lines.push(
        `                        _describe '${command.name} subcommand' subcmds`,
      );
      lines.push("                    else");
      lines.push('                        case "$subcmd" in');
      for (const sub of command.subcommands) {
        const hasSubOptions = sub.options && sub.options.length > 0;
        const isPathSub = sub.completionType === "path";
        if (!hasSubOptions && !isPathSub) continue;
        lines.push(`                            ${sub.name})`);
        const argParts = globalOptions.map(
          (option) =>
            `                                    ${zshOption(option)}`,
        );
        for (const option of sub.options ?? []) {
          argParts.push(
            `                                    ${zshOption(option)}`,
          );
        }
        if (isPathSub) {
          argParts.push(
            "                                    '*:path:_files -/'",
          );
        }
        lines.push(
          `                                _arguments \\\n${argParts.join(" \\\n")}`,
        );
        lines.push("                                ;;");
      }
      lines.push("                        esac");
      lines.push("                    fi");
      lines.push("                    ;;");
    }
  }

  for (const command of COMMANDS) {
    if (command.subcommands) continue;
    const names = getAllNames(command);
    const isBranchCommand = names.some((name) => branchCommands.includes(name));
    const isWorktreeCommand = names.some((name) =>
      worktreeCommands.includes(name),
    );
    lines.push(`                ${names.join("|")})`);
    lines.push("                    _arguments \\");
    const optionLines = [...globalOptions, ...(command.options ?? [])].map(
      (option) => `                        ${zshOption(option)}`,
    );
    if (isBranchCommand || isWorktreeCommand) {
      optionLines.push(
        `                        '*:branch:${isWorktreeCommand ? "_wct_worktree_branches" : "_wct_branches"}'`,
      );
    }
    lines.push(optionLines.join(" \\\n"));
    lines.push("                    ;;");
  }

  lines.push("            esac");
  lines.push("            ;;");
  lines.push("    esac");
  lines.push("}");
  lines.push("");
  lines.push("compdef _wct wct");
  lines.push("");

  return lines.join("\n");
}

export function generateCompletionScript(
  shell: "fish" | "bash" | "zsh",
): string {
  switch (shell) {
    case "fish":
      return generateFishCompletions();
    case "bash":
      return generateBashCompletions();
    case "zsh":
      return generateZshCompletions();
  }
}

export function getCustomCompletionShell(
  args: ReadonlyArray<string>,
): (typeof COMPLETION_SHELLS)[number] | null {
  for (let index = 0; index < args.length; index++) {
    const arg = args[index];
    if (arg === undefined) {
      continue;
    }

    if (arg === "--completions") {
      const shell = args[index + 1];
      return COMPLETION_SHELLS.find((supported) => supported === shell) ?? null;
    }

    if (!arg.startsWith("--completions=")) {
      continue;
    }

    const shell = arg.slice("--completions=".length);
    return COMPLETION_SHELLS.find((supported) => supported === shell) ?? null;
  }

  return null;
}
